import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error' && /THREE|WebGL|shader/i.test(message.text())) errors.push(message.text()); });
const canvas = page.locator('.anatomy-canvas canvas');
const shot = async () => createHash('sha256').update(await canvas.screenshot()).digest('hex');
const setSlider = async (name, value) => { const slider = page.getByRole('slider', { name, exact: true }); await slider.fill(String(value)); await slider.dispatchEvent('input'); };
await mkdir('/tmp/asthma-validation', { recursive: true });
try {
  await page.goto(process.env.TEST_URL || 'http://127.0.0.1:5190');
  await expect(page.locator('.anatomy-viewer')).toHaveAttribute('data-ready', 'true', { timeout: 30000 });
  await page.getByRole('button', { name: 'Pause simulation', exact: true }).click();
  await expect(canvas).toBeVisible();
  const front = await shot();
  await canvas.focus(); await page.keyboard.press('ArrowRight');
  await page.waitForTimeout(350);
  expect(await shot()).not.toBe(front);
  await page.getByRole('button', { name: 'Reset view', exact: true }).click();
  await setSlider('Lung tissue opacity', 0);
  await page.getByRole('button', { name: 'Rib cage', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Rib cage', exact: true })).toHaveAttribute('aria-pressed', 'false');
  await setSlider('Lung tissue opacity', 18);
  await page.getByRole('button', { name: 'Rib cage', exact: true }).click();
  await page.locator('.twin-panel').screenshot({ path: '/tmp/asthma-validation/anatomy-3d.png' });
  await page.getByRole('tab', { name: 'Wall cutaway' }).click();
  await setSlider('Mucus level', 0);
  const lowArea = Number.parseInt(await page.getByTestId('section-open-area').innerText());
  const lowContour = await page.getByTestId('current-lumen-path').getAttribute('d');
  const lowMucus = await shot();
  await setSlider('Mucus level', 100);
  await expect.poll(async () => Number.parseInt(await page.getByTestId('section-open-area').innerText())).toBeLessThan(lowArea * .8);
  expect(await page.getByTestId('current-lumen-path').getAttribute('d')).not.toBe(lowContour);
  expect(await shot()).not.toBe(lowMucus);
  await page.locator('.twin-panel').screenshot({ path: '/tmp/asthma-validation/mucus-cutaway.png' });
  const mucusVisible = await shot();
  await page.getByRole('button', { name: 'Mucus', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Mucus', exact: true })).toHaveAttribute('aria-pressed', 'false');
  expect(await shot()).not.toBe(mucusVisible);
  await page.getByRole('button', { name: 'Mucus', exact: true }).click();
  await page.getByRole('button', { name: 'Separate layers', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Separate layers', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Separate layers', exact: true }).click();
  await page.getByRole('button', { name: 'Severe Attack', exact: true }).click();
  await page.getByRole('button', { name: 'Pause simulation', exact: true }).click();
  const bronchusArea = Number.parseInt(await page.getByTestId('lumen-area').innerText());
  await page.getByRole('combobox', { name: 'Inspect airway region' }).selectOption('trachea');
  expect(Number.parseInt(await page.getByTestId('lumen-area').innerText())).toBeGreaterThan(bronchusArea * 3);
  await page.getByRole('combobox', { name: 'Inspect airway region' }).selectOption('bronchiole');
  await page.getByRole('tab', { name: 'Inside airway' }).click();
  await expect(page.locator('.anatomy-viewer')).toHaveAttribute('data-view', 'endoscopy');
  await page.locator('.twin-panel').screenshot({ path: '/tmp/asthma-validation/airway-endoscopy.png' });
  await page.getByRole('button', { name: 'Expand anatomy', exact: true }).click();
  await expect(page.locator('.anatomy-viewer')).toHaveClass(/expanded/);
  await page.keyboard.press('Escape');
  await expect(page.locator('.anatomy-viewer')).not.toHaveClass(/expanded/);
  await page.getByRole('button', { name: 'Healthy', exact: true }).click();
  await page.getByRole('tab', { name: '3D anatomy' }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Reset view', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.locator('.twin-panel').screenshot({ path: '/tmp/asthma-validation/anatomy-mobile.png' });
  expect(errors).toEqual([]);
  console.log('PASS: rendered 3D anatomy, camera rotation, opacity and rib toggles, mucus-driven lumen geometry, 3D layer visibility, separated layers, region sensitivity, endoscopy, expanded view and mobile layout; no WebGL or JavaScript errors.');
} finally { await browser.close(); }
